function validMonth(month) {
  return /^\d{4}-(0[1-9]|1[0-2])$/.test(
    month || ''
  );
}


function cleanNick(value) {
  return String(value || '')
    .normalize('NFKC')
    .trim()
    .replace(/\s+/g, ' ')
    .slice(0, 20);
}


function nickKeyOf(nickname) {
  return cleanNick(nickname)
    .toLocaleLowerCase('ko-KR');
}


function hdr(req, name) {
  try {
    return decodeURIComponent(
      String(req.headers[name] || '')
    );
  } catch {
    return '';
  }
}


// ============================================================
// Cookie
// ============================================================

function getCookie(req, name) {
  const cookies = String(
    req.headers.cookie || ''
  ).split(';');

  for (const part of cookies) {
    const i = part.indexOf('=');

    if (i < 0) continue;

    const key = part
      .slice(0, i)
      .trim();

    if (key !== name) continue;

    try {
      return decodeURIComponent(
        part.slice(i + 1).trim()
      );
    } catch {
      return '';
    }
  }

  return '';
}


// ============================================================
// 세션
// ============================================================

function sign(payload) {
  return crypto
    .createHmac(
      'sha256',
      SESSION_SECRET
    )
    .update(payload)
    .digest();
}


function setSession(res, userId) {
  const payload = Buffer
    .from(
      JSON.stringify({
        sub: userId,
        exp: Date.now() + SESSION_MS,
      })
    )
    .toString('base64url');

  const signature = sign(payload)
    .toString('base64url');

  const secure =
    process.env.NODE_ENV === 'production'
      ? '; Secure'
      : '';

  res.setHeader(
    'Set-Cookie',

    `session=${payload}.${signature}; ` +
    `Path=/; ` +
    `HttpOnly; ` +
    `SameSite=Strict; ` +
    `Max-Age=${Math.floor(SESSION_MS / 1000)}` +
    secure
  );
}


function clearSession(res) {
  const secure =
    process.env.NODE_ENV === 'production'
      ? '; Secure'
      : '';

  res.setHeader(
    'Set-Cookie',

    `session=; ` +
    `Path=/; ` +
    `HttpOnly; ` +
    `SameSite=Strict; ` +
    `Max-Age=0` +
    secure
  );
}


async function authenticatedUser(req) {
  const token = getCookie(
    req,
    'session'
  );

  const separator =
    token.lastIndexOf('.');

  if (separator < 1) {
    return null;
  }

  const payload =
    token.slice(0, separator);

  let suppliedSignature;

  try {
    suppliedSignature =
      Buffer.from(
        token.slice(separator + 1),
        'base64url'
      );
  } catch {
    return null;
  }

  const expectedSignature =
    sign(payload);

  if (
    suppliedSignature.length !==
    expectedSignature.length
  ) {
    return null;
  }

  if (
    !crypto.timingSafeEqual(
      suppliedSignature,
      expectedSignature
    )
  ) {
    return null;
  }

  try {
    const data = JSON.parse(
      Buffer.from(
        payload,
        'base64url'
      ).toString()
    );

    if (
      !data.sub ||
      !Number.isFinite(data.exp) ||
      data.exp < Date.now()
    ) {
      return null;
    }

    const result = await db.query(
      `
      SELECT
        id,
        nickname,
        nick_key
      FROM users
      WHERE id = $1
      `,
      [data.sub]
    );

    return result.rows[0] || null;
  } catch {
    return null;
  }
}


async function requireUser(req, res) {
  const user =
    await authenticatedUser(req);

  if (!user) {
    send(res, 401, {
      error: '먼저 로그인해주세요.',
    });

    return null;
  }

  return user;
}


// ============================================================
// PIN
// ============================================================

function pinHash(pin, salt) {
  return crypto.scryptSync(
    pin,
    salt,
    64
  );
}


// ============================================================
// 로그인 제한
// ============================================================

function attemptBucket(req, nickKey) {
  const ip =
    req.socket.remoteAddress ||
    'unknown';

  return crypto
    .createHmac(
      'sha256',
      SESSION_SECRET
    )
    .update(`${nickKey}\n${ip}`)
    .digest('hex');
}


async function isLoginBlocked(bucket) {
  const result = await db.query(
    `
    SELECT blocked_until
    FROM login_attempts
    WHERE bucket = $1
    `,
    [bucket]
  );

  const row = result.rows[0];

  return Boolean(
    row &&
    Number(row.blocked_until) >
      Date.now()
  );
}


async function failLogin(bucket) {
  const now = Date.now();

  const result = await db.query(
    `
    SELECT
      count,
      window_started
    FROM login_attempts
    WHERE bucket = $1
    `,
    [bucket]
  );

  const row = result.rows[0];

  const inWindow =
    row &&
    now - Number(row.window_started) <
      LOGIN_WINDOW_MS;

  const count =
    inWindow
      ? Number(row.count) + 1
      : 1;

  const windowStarted =
    inWindow
      ? Number(row.window_started)
      : now;

  const blockedUntil =
    count >= LOGIN_MAX_ATTEMPTS
      ? now + LOGIN_BLOCK_MS
      : 0;

  await db.query(
    `
    INSERT INTO login_attempts
      (
        bucket,
        count,
        window_started,
        blocked_until
      )
    VALUES
      ($1, $2, $3, $4)

    ON CONFLICT(bucket)
    DO UPDATE SET
      count = EXCLUDED.count,
      window_started = EXCLUDED.window_started,
      blocked_until = EXCLUDED.blocked_until
    `,
    [
      bucket,
      count,
      windowStarted,
      blockedUntil,
    ]
  );
}


// ============================================================
// 이미지 파일 형식 검사
// ============================================================

function sniff(buffer) {
  // JPEG
  if (
    buffer.length > 3 &&
    buffer[0] === 0xff &&
    buffer[1] === 0xd8 &&
    buffer[2] === 0xff
  ) {
    return 'jpg';
  }

  // PNG
  if (
    buffer.length >= 8 &&
    buffer.subarray(0, 8).equals(
      Buffer.from([
        0x89,
        0x50,
        0x4e,
        0x47,
        0x0d,
        0x0a,
        0x1a,
        0x0a,
      ])
    )
  ) {
    return 'png';
  }

  // WEBP
  if (
    buffer.length >= 12 &&
    buffer.subarray(0, 4).toString() ===
      'RIFF' &&
    buffer.subarray(8, 12).toString() ===
      'WEBP'
  ) {
    return 'webp';
  }

  return null;
}


function contentTypeFor(extension) {
  switch (extension) {
    case 'jpg':
      return 'image/jpeg';

    case 'png':
      return 'image/png';

    case 'webp':
      return 'image/webp';

    default:
      return 'application/octet-stream';
  }
}


