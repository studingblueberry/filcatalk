async function api(req, res, url) {
  const pathname = url.pathname;
  const method = req.method;
  let match;

  // 서버 설정
  if (pathname === '/api/config' && method === 'GET') {
    return send(res, 200, {
      maxPerUser: MAX_PER_USER,
      maxImageMB: MAX_IMAGE_MB,
    });
  }

  // 관리자 확인
  if (pathname === '/api/admin/check' && method === 'GET') {
    const admin = isAdmin(req);
    return send(res, admin ? 200 : 401, { admin });
  }

  // 현재 로그인 사용자
  if (pathname === '/api/me' && method === 'GET') {
    const user = await authenticatedUser(req);

    return send(res, 200, {
      user: user
        ? { id: user.id, nickname: user.nickname }
        : null,
    });
  }

  // 회원가입
  if (pathname === '/api/register' && method === 'POST') {
    const body = await readJson(req);
    const nickname = cleanNick(body.nickname);
    const nickKey = nickKeyOf(nickname);
    const pin = String(body.pin || '');

    if (!nickname) {
      return send(res, 400, {
        error: '닉네임을 입력해주세요.',
      });
    }

    if (!/^\d{4}$/.test(pin)) {
      return send(res, 400, {
        error: '비밀번호는 숫자 4자리로 입력해주세요.',
      });
    }

    const id = crypto.randomUUID();
    const salt = crypto.randomBytes(16).toString('hex');
    const hash = pinHash(pin, salt).toString('hex');

    try {
      await db.query(
        `
        INSERT INTO users
          (id, nickname, nick_key, pin_salt, pin_hash)
        VALUES ($1, $2, $3, $4, $5)
        `,
        [id, nickname, nickKey, salt, hash]
      );
    } catch (error) {
      if (error.code === '23505') {
        return send(res, 409, {
          error: '이미 사용 중인 닉네임입니다.',
        });
      }

      throw error;
    }

    setSession(res, id);

    return send(res, 201, {
      user: { id, nickname },
    });
  }

  // 로그인
  if (pathname === '/api/login' && method === 'POST') {
    const body = await readJson(req);
    const nickname = cleanNick(body.nickname);
    const nickKey = nickKeyOf(nickname);
    const pin = String(body.pin || '');
    const bucket = attemptBucket(req, nickKey);

    if (await isLoginBlocked(bucket)) {
      return send(res, 429, {
        error: '로그인 시도가 제한되었습니다. 잠시 후 다시 시도해주세요.',
      });
    }

    const result = await db.query(
      `
      SELECT id, nickname, pin_salt, pin_hash
      FROM users
      WHERE nick_key = $1
      `,
      [nickKey]
    );

    const user = result.rows[0];
    const salt = user?.pin_salt || 'unknown-user-salt';

    const expected = user
      ? Buffer.from(user.pin_hash, 'hex')
      : pinHash('0000', salt);

    const candidate = pinHash(
      /^\d{4}$/.test(pin) ? pin : '0000',
      salt
    );

    const valid =
      Boolean(user) &&
      expected.length === candidate.length &&
      crypto.timingSafeEqual(expected, candidate);

    if (!valid) {
      await failLogin(bucket);

      return send(res, 401, {
        error: '닉네임 또는 비밀번호가 올바르지 않습니다.',
      });
    }

    await db.query(
      `DELETE FROM login_attempts WHERE bucket = $1`,
      [bucket]
    );

    setSession(res, user.id);

    return send(res, 200, {
      user: { id: user.id, nickname: user.nickname },
    });
  }

  // 로그아웃
  if (pathname === '/api/logout' && method === 'POST') {
    clearSession(res);
    return send(res, 200, { ok: true });
  }

  // ----------------------------------------------------------
  // 사진 목록: ?season=spring|summer|autumn|winter
  // 이전 요청 ?month=YYYY-MM 도 임시 지원
  // ----------------------------------------------------------

  if (pathname === '/api/photos' && method === 'GET') {
    let season = url.searchParams.get('season');

    if (!season) {
      season = seasonFromMonth(url.searchParams.get('month'));
    }

    if (!validSeason(season)) {
      return send(res, 400, {
        error: '올바른 계절이 아닙니다.',
      });
    }

    const admin = isAdmin(req);
    const user = await authenticatedUser(req);

    const photos = await listPhotos(
      season,
      user?.id || '',
      admin,
      user?.id || ''
    );

    let mine = 0;

    if (user) {
      const result = await db.query(
        `SELECT COUNT(*) AS c FROM photos WHERE owner_id = $1`,
        [user.id]
      );

      mine = Number(result.rows[0].c);
    }

    return send(res, 200, {
      photos,
      mine,
      admin,
      season,
      user: user
        ? { id: user.id, nickname: user.nickname }
        : null,
    });
  }

  // ----------------------------------------------------------
  // 사진 업로드: x-season 헤더 사용
  // 이전 x-month 헤더도 임시 지원
  // ----------------------------------------------------------

  if (pathname === '/api/photos' && method === 'POST') {
    const user = await requireUser(req, res);

    if (!user) {
      req.resume();
      return;
    }

    const suppliedSeason = hdr(req, 'x-season');
    const legacyMonth = hdr(req, 'x-month');

    const season = suppliedSeason
      ? suppliedSeason
      : seasonFromMonth(legacyMonth);

    if (!validSeason(season)) {
      req.resume();

      return send(res, 400, {
        error: '올바른 계절이 아닙니다.',
      });
    }

    // 구형 프론트엔드의 월 정보만 기존 방식으로 보존
    const monthToSave =
      !suppliedSeason && validMonth(legacyMonth)
        ? legacyMonth
        : null;

    const contentLength = Number(req.headers['content-length'] || 0);

    if (contentLength > MAX_BYTES) {
      req.resume();

      return send(res, 413, {
        error: `사진은 장당 ${MAX_IMAGE_MB}MB까지 올릴 수 있어요.`,
      });
    }

    const countResult = await db.query(
      `SELECT COUNT(*) AS c FROM photos WHERE owner_id = $1`,
      [user.id]
    );

    const count = Number(countResult.rows[0].c);

    if (count >= MAX_PER_USER) {
      req.resume();

      return send(res, 409, {
        error: `한 사람당 전체 ${MAX_PER_USER}장까지만 올릴 수 있어요.`,
      });
    }

    const buffer = await readBody(req, MAX_BYTES);
    const extension = sniff(buffer);

    if (!extension) {
      return send(res, 400, {
        error: 'JPG, PNG, WEBP 이미지만 올릴 수 있어요.',
      });
    }

    const filename = `${crypto.randomUUID()}.${extension}`;
    const contentType = contentTypeFor(extension);

    await uploadToR2(filename, buffer, contentType);

    try {
      const result = await db.query(
        `
        INSERT INTO photos
          (
            month,
            season,
            nickname,
            nick_key,
            caption,
            filename,
            owner_id
          )
        VALUES ($1, $2, $3, $4, $5, $6, $7)
        RETURNING id
        `,
        [
          monthToSave,
          season,
          user.nickname,
          user.nick_key,
          '',
          filename,
          user.id,
        ]
      );

      return send(res, 201, {
        id: Number(result.rows[0].id),
        mine: count + 1,
      });
    } catch (error) {
      // DB 저장 실패 시 R2에 업로드한 파일 정리
      try {
        await deleteFromR2(filename);
      } catch (cleanupError) {
        console.error('R2 정리 실패:', cleanupError);
      }

      throw error;
    }
  }

  // 썸네일 업로드
  if (
    (match = /^\/api\/photos\/(\d+)\/thumb$/.exec(pathname)) &&
    method === 'POST'
  ) {
    const user = await requireUser(req, res);

    if (!user) {
      req.resume();
      return;
    }

    const id = Number(match[1]);

    const result = await db.query(
      `SELECT owner_id, thumb FROM photos WHERE id = $1`,
      [id]
    );

    const row = result.rows[0];

    if (!row) {
      req.resume();

      return send(res, 404, {
        error: '사진을 찾을 수 없어요.',
      });
    }

    if (row.owner_id !== user.id || row.thumb) {
      req.resume();

      return send(res, 403, {
        error: '권한이 없어요.',
      });
    }

    const buffer = await readBody(req, 2 * 1024 * 1024);

    if (sniff(buffer) !== 'jpg') {
      return send(res, 400, {
        error: '썸네일은 JPG만 가능해요.',
      });
    }

    const filename = `t-${crypto.randomUUID()}.jpg`;

    await uploadToR2(filename, buffer, 'image/jpeg');

    try {
      const update = await db.query(
        `
        UPDATE photos
        SET thumb = $1
        WHERE id = $2 AND owner_id = $3 AND thumb = ''
        `,
        [filename, id, user.id]
      );

      // 기존 thumb 값이 NULL인 행도 허용
      if (update.rowCount === 0) {
        const retry = await db.query(
          `
          UPDATE photos
          SET thumb = $1
          WHERE id = $2 AND owner_id = $3 AND thumb IS NULL
          `,
          [filename, id, user.id]
        );

        if (retry.rowCount === 0) {
          await deleteFromR2(filename);

          return send(res, 409, {
            error: '썸네일이 이미 등록되었거나 사진을 찾을 수 없어요.',
          });
        }
      }
    } catch (error) {
      try {
        await deleteFromR2(filename);
      } catch (cleanupError) {
        console.error('R2 썸네일 정리 실패:', cleanupError);
      }

      throw error;
    }

    return send(res, 200, { ok: true });
  }

  // 투표
  if (
    (match = /^\/api\/photos\/(\d+)\/vote$/.exec(pathname)) &&
    method === 'POST'
  ) {
    const user = await requireUser(req, res);

    if (!user) return;

    const id = Number(match[1]);

    const photoResult = await db.query(
      `SELECT owner_id FROM photos WHERE id = $1`,
      [id]
    );

    const photo = photoResult.rows[0];

    if (!photo) {
      return send(res, 404, {
        error: '사진을 찾을 수 없어요.',
      });
    }

    if (photo.owner_id && photo.owner_id === user.id) {
      return send(res, 403, {
        error: '내 사진에는 투표할 수 없어요.',
      });
    }

    const voteResult = await db.query(
      `
      SELECT 1
      FROM votes
      WHERE photo_id = $1 AND voter_id = $2
      `,
      [id, user.id]
    );

    const had = voteResult.rowCount > 0;

    if (had) {
      await db.query(
        `
        DELETE FROM votes
        WHERE photo_id = $1 AND voter_id = $2
        `,
        [id, user.id]
      );
    } else {
      await db.query(
        `
        INSERT INTO votes (photo_id, voter_id)
        VALUES ($1, $2)
        ON CONFLICT (photo_id, voter_id) DO NOTHING
        `,
        [id, user.id]
      );
    }

    return send(res, 200, {
      voted: !had,
    });
  }

  // 사진 삭제
  if (
    (match = /^\/api\/photos\/(\d+)$/.exec(pathname)) &&
    method === 'DELETE'
  ) {
    const id = Number(match[1]);
    const admin = isAdmin(req);
    const user = await authenticatedUser(req);

    const result = await db.query(
      `SELECT owner_id FROM photos WHERE id = $1`,
      [id]
    );

    const row = result.rows[0];

    if (!row) {
      return send(res, 200, { ok: true });
    }

    const isOwner = Boolean(user) && row.owner_id === user.id;

    if (!admin && !isOwner) {
      return send(res, 403, {
        error: '본인이 올린 사진만 삭제할 수 있어요.',
      });
    }

    await removePhoto(id);

    return send(res, 200, { ok: true });
  }

  // 관리자 사진 목록과 북마크는 모두 PostgreSQL에 보관합니다.
  if (pathname.startsWith('/api/admin/')) {
    if (!isAdmin(req)) {
      return send(res, 401, {
        error: '관리자 키가 필요해요.',
      });
    }

    if (pathname === '/api/admin/bookmarks' && method === 'GET') {
      const result = await db.query(
        `SELECT p.id, CASE WHEN p.month ~ '^\\d{4}-(0[1-9]|1[0-2])$' THEN p.month
                  ELSE TO_CHAR(p.created_at, 'YYYY-MM') END AS photo_month,
          p.nickname, p.caption, p.filename, p.thumb,
          p.created_at,
          TRUE AS bookmarked,
          (SELECT COUNT(*)::int FROM votes v WHERE v.photo_id = p.id) AS votes
         FROM photos p JOIN admin_bookmarks b ON b.photo_id = p.id
         ORDER BY b.created_at DESC, p.id DESC`
      );
      return send(res, 200, { photos: result.rows.map(adminPhoto) });
    }

    if (pathname === '/api/admin/bookmarks' && method === 'POST') {
      const body = await readJson(req);
      const id = Number(body.photoId);
      if (!Number.isSafeInteger(id) || id < 1) {
        return send(res, 400, { error: '사진 정보가 올바르지 않아요.' });
      }
      const saved = await db.query(
        `INSERT INTO admin_bookmarks(photo_id) SELECT id FROM photos WHERE id = $1
         ON CONFLICT(photo_id) DO NOTHING RETURNING photo_id`, [id]
      );
      if (!saved.rowCount && !(await db.query('SELECT 1 FROM photos WHERE id = $1', [id])).rowCount) {
        return send(res, 404, { error: '사진을 찾을 수 없어요.' });
      }
      return send(res, 200, { bookmarked: true });
    }

    if ((match = /^\/api\/admin\/bookmarks\/(\d+)$/.exec(pathname)) && method === 'DELETE') {
      await db.query('DELETE FROM admin_bookmarks WHERE photo_id = $1', [Number(match[1])]);
      return send(res, 200, { bookmarked: false });
    }

    if (pathname === '/api/admin/photos' && method === 'GET') {
      const month = url.searchParams.get('month');
      if (!validMonth(month)) return send(res, 400, { error: '올바른 월이 아닙니다.' });
      const result = await db.query(
        `SELECT p.id, CASE WHEN p.month ~ '^\\d{4}-(0[1-9]|1[0-2])$' THEN p.month
                  ELSE TO_CHAR(p.created_at, 'YYYY-MM') END AS photo_month,
          p.nickname, p.caption, p.filename, p.thumb, p.created_at,
          (SELECT COUNT(*)::int FROM votes v WHERE v.photo_id = p.id) AS votes,
          EXISTS(SELECT 1 FROM admin_bookmarks b WHERE b.photo_id = p.id) AS bookmarked
         FROM photos p
         WHERE CASE WHEN p.month ~ '^\\d{4}-(0[1-9]|1[0-2])$' THEN p.month
                    ELSE TO_CHAR(p.created_at, 'YYYY-MM') END = $1
         ORDER BY votes DESC, p.id DESC`, [month]
      );
      return send(res, 200, { photos: result.rows.map(adminPhoto) });
    }

    if ((match = /^\/api\/admin\/photos\/(\d+)\/download$/.exec(pathname)) && method === 'GET') {
      const photo = (await db.query('SELECT filename FROM photos WHERE id = $1', [Number(match[1])])).rows[0];
      if (!photo) return send(res, 404, { error: '사진을 찾을 수 없어요.' });
      const object = await r2.send(new GetObjectCommand({ Bucket: R2_BUCKET, Key: photo.filename }));
      const safeName = `filcatalk_${Number(match[1])}${path.extname(photo.filename).toLowerCase()}`;
      res.writeHead(200, {
        'Content-Type': contentTypeFor(path.extname(photo.filename).slice(1)),
        'Content-Disposition': `attachment; filename="${safeName}"`,
        'Cache-Control': 'private, no-store',
        'X-Content-Type-Options': 'nosniff',
      });
      object.Body.on('error', (error) => {
        console.error('R2 원본 다운로드 실패:', error);
        if (!res.headersSent) send(res, 502, { error: '원본을 내려받지 못했어요.' });
        else res.destroy(error);
      });
      object.Body.pipe(res);
      return;
    }

    if (pathname === '/api/admin/ranking' && method === 'GET') {
      const result = await db.query(
        `SELECT p.id,
          CASE WHEN p.month ~ '^\\d{4}-(0[1-9]|1[0-2])$' THEN p.month
               ELSE TO_CHAR(p.created_at, 'YYYY-MM') END AS photo_month,
          p.nickname, p.caption, p.filename, p.thumb, p.created_at,
          (SELECT COUNT(*)::int FROM votes v WHERE v.photo_id = p.id) AS votes,
          EXISTS(SELECT 1 FROM admin_bookmarks b WHERE b.photo_id = p.id) AS bookmarked
         FROM photos p
         ORDER BY photo_month DESC, votes DESC, p.id DESC`
      );
      const byMonth = new Map();
      for (const row of result.rows) {
        const month = row.photo_month;
        if (!byMonth.has(month)) byMonth.set(month, { month, total: 0, ranks: [], photos: [] });
        const group = byMonth.get(month);
        const photo = adminPhoto(row);
        group.total++;
        group.photos.push(photo);
        const votes = Number(row.votes);
        if (votes < 1) continue;
        let rank = group.ranks.find((item) => item.votes === votes);
        if (!rank && group.ranks.length < 3) {
          rank = { rank: group.ranks.length + 1, votes, photos: [] };
          group.ranks.push(rank);
        }
        if (rank) rank.photos.push(photo);
      }
      return send(res, 200, { months: [...byMonth.values()] });
    }
  }

  return send(res, 404, {
    error: 'not found',
  });
}

