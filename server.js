function sniff(buffer) {
  if (
    buffer.length > 3 &&
    buffer[0] === 0xff &&
    buffer[1] === 0xd8 &&
    buffer[2] === 0xff
  ) {
    return 'jpg';
  }

  if (
    buffer.length >= 8 &&
    buffer.subarray(0, 8).equals(
      Buffer.from([
        0x89, 0x50, 0x4e, 0x47,
        0x0d, 0x0a, 0x1a, 0x0a,
      ])
    )
  ) {
    return 'png';
  }

  if (
    buffer.length >= 12 &&
    buffer.subarray(0, 4).toString() === 'RIFF' &&
    buffer.subarray(8, 12).toString() === 'WEBP'
  ) {
    return 'webp';
  }

  return null;
}

function contentTypeFor(extension) {
  switch (extension) {
    case 'jpg': return 'image/jpeg';
    case 'png': return 'image/png';
    case 'webp': return 'image/webp';
    default: return 'application/octet-stream';
  }
}

function urlOf(filename) {
  return (
    R2_PUBLIC_URL.replace(/\/$/, '') +
    '/' +
    encodeURIComponent(filename)
  );
}

function adminPhoto(row) {
  return {
    id: Number(row.id),
    month: row.photo_month || row.month || '',
    nickname: row.nickname,
    caption: row.caption || '',
    url: urlOf(row.filename),
    thumb: row.thumb ? urlOf(row.thumb) : urlOf(row.filename),
    votes: Number(row.votes || 0),
    bookmarked: Boolean(row.bookmarked),
    createdAt: row.created_at,
  };
}

async function uploadToR2(filename, buffer, contentType) {
  await r2.send(
    new PutObjectCommand({
      Bucket: R2_BUCKET,
      Key: filename,
      Body: buffer,
      ContentType: contentType,
    })
  );
}

async function deleteFromR2(filename) {
  if (!filename) return;

  await r2.send(
    new DeleteObjectCommand({
      Bucket: R2_BUCKET,
      Key: filename,
    })
  );
}

