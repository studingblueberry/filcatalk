function pinHash(pin, salt) {
  return crypto.scryptSync(pin, salt, 64);
}

function attemptBucket(req, nickKey) {
  const ip = req.socket.remoteAddress || 'unknown';

  return crypto
    .createHmac('sha256', SESSION_SECRET)
    .update(`${nickKey}\n${ip}`)
    .digest('hex');
}

async function isLoginBlocked(bucket) {
  const result = await db.query(
    `SELECT blocked_until FROM login_attempts WHERE bucket = $1`,
    [bucket]
  );

  const row = result.rows[0];

  return Boolean(row && Number(row.blocked_until) > Date.now());
}

async function failLogin(bucket) {
  const now = Date.now();

  const result = await db.query(
    `
    SELECT count, window_started
    FROM login_attempts
    WHERE bucket = $1
    `,
    [bucket]
  );

  const row = result.rows[0];

  const inWindow =
    row && now - Number(row.window_started) < LOGIN_WINDOW_MS;

  const count = inWindow ? Number(row.count) + 1 : 1;
  const windowStarted = inWindow ? Number(row.window_started) : now;

  const blockedUntil =
    count >= LOGIN_MAX_ATTEMPTS ? now + LOGIN_BLOCK_MS : 0;

  await db.query(
    `
    INSERT INTO login_attempts
      (bucket, count, window_started, blocked_until)
    VALUES ($1, $2, $3, $4)
    ON CONFLICT(bucket)
    DO UPDATE SET
      count = EXCLUDED.count,
      window_started = EXCLUDED.window_started,
      blocked_until = EXCLUDED.blocked_until
    `,
    [bucket, count, windowStarted, blockedUntil]
  );
}

