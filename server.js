async function removePhoto(id) {
  const result = await db.query(
    `SELECT filename, thumb FROM photos WHERE id = $1`,
    [id]
  );

  const row = result.rows[0];
  if (!row) return;

  // votes는 FK의 ON DELETE CASCADE에 의해 함께 삭제된다.
  await db.query(`DELETE FROM photos WHERE id = $1`, [id]);

  for (const filename of [row.filename, row.thumb]) {
    if (!filename) continue;

    try {
      await deleteFromR2(filename);
    } catch (error) {
      console.error('R2 파일 삭제 실패:', filename, error);
    }
  }
}

