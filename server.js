async function initializeDatabase() {
  await db.query(`
    CREATE TABLE IF NOT EXISTS users (
      id TEXT PRIMARY KEY,
      nickname TEXT NOT NULL,
      nick_key TEXT NOT NULL UNIQUE,
      pin_salt TEXT NOT NULL,
      pin_hash TEXT NOT NULL,
      created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
    )
  `);

  await db.query(`
    CREATE TABLE IF NOT EXISTS photos (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      month TEXT,
      season TEXT,
      nickname TEXT NOT NULL,
      nick_key TEXT NOT NULL,
      caption TEXT DEFAULT '',
      filename TEXT NOT NULL,
      created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
      owner_id TEXT DEFAULT '',
      thumb TEXT DEFAULT ''
    )
  `);

  // 기존 데이터베이스에 season 컬럼 추가
  await db.query(`
    ALTER TABLE photos
    ADD COLUMN IF NOT EXISTS season TEXT
  `);

  // month의 월 문자열을 기준으로 기존 사진을 계절로 변환.
  // 문자열 비교를 사용하여 잘못된 month 값의 정수 변환 오류를 방지.
  // 이미 season 값이 있는 사진은 덮어쓰지 않는다.
  await db.query(`
    UPDATE photos
    SET season = CASE SUBSTRING(month FROM 6 FOR 2)
      WHEN '03' THEN 'spring'
      WHEN '04' THEN 'spring'
      WHEN '05' THEN 'spring'
      WHEN '06' THEN 'summer'
      WHEN '07' THEN 'summer'
      WHEN '08' THEN 'summer'
      WHEN '09' THEN 'autumn'
      WHEN '10' THEN 'autumn'
      WHEN '11' THEN 'autumn'
      WHEN '12' THEN 'winter'
      WHEN '01' THEN 'winter'
      WHEN '02' THEN 'winter'
      ELSE NULL
    END
    WHERE season IS NULL
      AND month ~ '^\\d{4}-(0[1-9]|1[0-2])$'
  `);

  // 새 업로드는 month 없이 저장한다.
  // 기존 사진의 month 값은 삭제하지 않는다.
  await db.query(`
    ALTER TABLE photos
    ALTER COLUMN month DROP NOT NULL
  `);

  await db.query(`
    CREATE INDEX IF NOT EXISTS idx_photos_month
    ON photos(month)
  `);

  await db.query(`
    CREATE INDEX IF NOT EXISTS idx_photos_season
    ON photos(season)
  `);

  await db.query(`
    CREATE TABLE IF NOT EXISTS votes (
      photo_id INTEGER NOT NULL
        REFERENCES photos(id)
        ON DELETE CASCADE,
      voter_id TEXT NOT NULL,
      created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
      PRIMARY KEY (photo_id, voter_id)
    )
  `);

  await db.query(`
    CREATE TABLE IF NOT EXISTS admin_bookmarks (
      photo_id INTEGER PRIMARY KEY REFERENCES photos(id) ON DELETE CASCADE,
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    )
  `);

  await db.query(`
    CREATE TABLE IF NOT EXISTS login_attempts (
      bucket TEXT PRIMARY KEY,
      count INTEGER NOT NULL DEFAULT 0,
      window_started BIGINT NOT NULL,
      blocked_until BIGINT NOT NULL DEFAULT 0
    )
  `);

  console.log('PostgreSQL 데이터베이스 초기화 완료');
}

