async function listPhotos(season, voterId, admin, ownerId) {
  const result = await db.query(
    `
    SELECT
      p.id,
      p.nickname,
      p.caption,
      p.filename,
      p.thumb,
      p.owner_id,

      (
        SELECT COUNT(*)
        FROM votes v
        WHERE v.photo_id = p.id
      ) AS votes,

      EXISTS(
        SELECT 1
        FROM votes v
        WHERE v.photo_id = p.id
          AND v.voter_id = $1
      ) AS voted

    FROM photos p
    WHERE p.season = $2
    ORDER BY p.id DESC
    `,
    [voterId || '', season]
  );

  return result.rows.map((row) => {
    const photo = {
      id: Number(row.id),
      nickname: row.nickname,
      caption: row.caption,
      url: urlOf(row.filename),
      thumb: row.thumb ? urlOf(row.thumb) : urlOf(row.filename),
      voted: Boolean(row.voted),
      own: Boolean(ownerId) && row.owner_id === ownerId,
    };

    if (admin) {
      photo.votes = Number(row.votes);
    }

    return photo;
  });
}

