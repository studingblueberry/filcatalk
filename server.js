// 서버 시작
// ============================================================

async function startServer() {
  try {

    // PostgreSQL 연결 테스트
    await db.query(
      'SELECT 1'
    );

    console.log(
      'PostgreSQL 연결 성공'
    );


    // 테이블 생성
    await initializeDatabase();


    // 서버 실행
    server.listen(
      PORT,
      () => {
        console.log(
          `필카톡 서버 실행 중: PORT ${PORT}`
        );

        console.log(
          `관리자 페이지: /admin`
        );

        console.log(
          `R2 Bucket: ${R2_BUCKET}`
        );
      }
    );

  } catch (error) {

    console.error(
      '서버 시작 실패:',
      error
    );

    process.exit(1);
  }
}


startServer();


