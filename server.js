const VALID_SEASONS = new Set([
  'spring',
  'summer',
  'autumn',
  'winter',
]);

function validSeason(season) {
  return VALID_SEASONS.has(season || '');
}

function validMonth(month) {
  return /^\d{4}-(0[1-9]|1[0-2])$/.test(month || '');
}

function seasonFromMonth(month) {
  if (!validMonth(month)) return null;

  const number = Number(month.slice(5, 7));

  if (number >= 3 && number <= 5) return 'spring';
  if (number >= 6 && number <= 8) return 'summer';
  if (number >= 9 && number <= 11) return 'autumn';

  return 'winter';
}

function cleanNick(value) {
  return String(value || '')
    .normalize('NFKC')
    .trim()
    .replace(/\s+/g, ' ')
    .slice(0, 20);
}

function nickKeyOf(nickname) {
  return cleanNick(nickname).toLocaleLowerCase('ko-KR');
}

function hdr(req, name) {
  try {
    return decodeURIComponent(String(req.headers[name] || ''));
  } catch {
    return '';
  }
}

